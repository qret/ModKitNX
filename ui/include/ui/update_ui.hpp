#pragma once

#include <functional>

#include "platform/app_update.hpp"

namespace mk::ui::update {

// При запуске (после первого экрана): если в настройках «Проверять при запуске» (по умолчанию да) — тихая
// проверка в фоне. Нет сети, ошибка, нет новой версии, версия пропущена — ничего не показывается (только журнал).
void startupCheck();

// «Проверить обновления» в настройках: то же, но с ответом всегда («у вас последняя версия», «не удалось
// проверить»), пропущенная версия предлагается снова.
void checkNow();

// Окно «Доступна версия X.Y.Z»: что нового, «Обновить» / «Пропустить эту версию» / «Не сейчас».
void showOffer(const mk::plat::update::Release& r);

}  // namespace mk::ui::update
